export type AvailableGreetingEmoji = {
  name: string;
  markup: string;
};

export function pickRandomGreeting(
  previousIndex: number | undefined,
  randomValue = Math.random(),
): { greeting: Greeting; index: number } {
  if (greetings.length === 0) {
    throw new Error("No greetings are configured.");
  }

  const normalizedRandom = Number.isFinite(randomValue)
    ? Math.min(Math.max(randomValue, 0), 0.9999999999999999)
    : 0;
  const canExcludePrevious =
    greetings.length > 1 &&
    previousIndex !== undefined &&
    Number.isInteger(previousIndex) &&
    previousIndex >= 0 &&
    previousIndex < greetings.length;
  const candidateCount = greetings.length - (canExcludePrevious ? 1 : 0);
  let index = Math.floor(normalizedRandom * candidateCount);

  if (canExcludePrevious && index >= previousIndex) {
    index += 1;
  }

  return {
    greeting: greetings[index],
    index,
  };
}

export function pickRandomGreetingEmoji(
  availableEmojis: readonly AvailableGreetingEmoji[],
  previousName: string | undefined,
  randomValue = Math.random(),
): AvailableGreetingEmoji | undefined {
  if (availableEmojis.length === 0) {
    return undefined;
  }

  const normalizedRandom = Number.isFinite(randomValue)
    ? Math.min(Math.max(randomValue, 0), 0.9999999999999999)
    : 0;
  const candidates =
    availableEmojis.length > 1 && previousName
      ? availableEmojis.filter((emoji) => emoji.name !== previousName)
      : availableEmojis;
  const usableCandidates =
    candidates.length > 0 ? candidates : availableEmojis;
  const index = Math.floor(normalizedRandom * usableCandidates.length);

  return usableCandidates[index];
}
